#!/usr/bin/env node
/**
 * Imports exercise METADATA from a local clone of https://github.com/hasaneyldrm/exercises-dataset
 * (CAT-01, O-02). Media (images/GIFs, media ids, attribution strings for media) is dropped: Gym visual
 * media is not covered by the dataset's MIT license and must never be bundled or hotlinked (O-01).
 *
 * Usage (from app/): node scripts/import-exercises.mjs <path-to-clone>
 * The clone must be checked out at PINNED_SHA; the script refuses anything else.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { z } from 'zod';

const SOURCE_URL = 'https://github.com/hasaneyldrm/exercises-dataset';
const PINNED_SHA = '7455efae41b330c265e7cd4b78dfa848e7ce5ebd';
const CATALOG_VERSION = 1;

const clone = process.argv[2];
if (!clone) {
  console.error('usage: node scripts/import-exercises.mjs <path-to-dataset-clone>');
  process.exit(2);
}
const sha = execFileSync('git', ['-C', clone, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
if (sha !== PINNED_SHA) throw new Error(`Dataset clone is at ${sha}, expected pinned ${PINNED_SHA}`);

const source = z
  .object({
    id: z.string().regex(/^[0-9]{4}$/),
    name: z.string().trim().min(1).max(100),
    body_part: z.string().min(1),
    equipment: z.string().min(1),
    target: z.string().min(1),
    secondary_muscles: z.array(z.string().min(1)),
    instruction_steps: z.object({ en: z.array(z.string().min(1)) }).passthrough(),
  })
  .passthrough();

const raw = JSON.parse(readFileSync(join(clone, 'data', 'exercises.json'), 'utf8'));
if (!Array.isArray(raw)) throw new Error('exercises.json is not an array');

const titleCase = (s) => s.replace(/(^|[\s(/-])([a-z])/g, (_, p, c) => p + c.toUpperCase());
const loadModeFor = (equipment) =>
  equipment === 'body weight' ? 'bodyweight' : equipment === 'assisted' ? 'assisted' : 'external';

const seen = new Set();
const exercises = raw.map((entry, i) => {
  const r = source.safeParse(entry);
  if (!r.success) throw new Error(`Entry ${i} invalid: ${r.error.message}`);
  const e = r.data;
  if (seen.has(e.id)) throw new Error(`Duplicate id ${e.id}`);
  seen.add(e.id);
  // Whitelisted fields only: image, gif_url, media_id and attribution never leave this script.
  return {
    sourceId: e.id,
    name: titleCase(e.name.trim()),
    bodyPart: e.body_part,
    target: e.target,
    primaryMuscles: [e.target],
    secondaryMuscles: e.secondary_muscles,
    equipment: [e.equipment],
    instructions: e.instruction_steps.en,
    loadMode: loadModeFor(e.equipment),
    mediaRights: 'unresolved',
  };
});
exercises.sort((a, b) => a.sourceId.localeCompare(b.sourceId));

const out = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'assets', 'catalog');
mkdirSync(out, { recursive: true });
const payload = { version: CATALOG_VERSION, source: { url: SOURCE_URL, sha: PINNED_SHA }, count: exercises.length, exercises };
const json = JSON.stringify(payload);
if (/\.(gif|jpe?g|png)\b|images\/|videos\//i.test(json)) throw new Error('Media reference leaked into catalog output');
writeFileSync(join(out, 'exercises.v1.json'), json + '\n');

const license = readFileSync(join(clone, 'LICENSE'), 'utf8');
const mitPart = license.split(/^-{10,}$/m)[0].trim();
writeFileSync(
  join(out, 'ATTRIBUTION.md'),
  `# Exercise catalog attribution

- Source: ${SOURCE_URL}
- Pinned commit: \`${PINNED_SHA}\`
- Imported entries: ${exercises.length} (catalog version ${CATALOG_VERSION})
- Generated by \`app/scripts/import-exercises.mjs\` (do not edit \`exercises.v1.json\` by hand)

Imported fields: id (kept as a string), name, body part, target, secondary muscles, equipment and the English
instruction steps. \`loadMode\` is derived from equipment (body weight -> bodyweight, assisted -> assisted,
otherwise external).

## Media is NOT included

The dataset's exercise images and GIFs are (c) Gym visual (https://gymvisual.com/). They are **not** covered
by the MIT license below, are **not** included in this app, are **not** hotlinked, and **no license to them is
held** by this project (docs/DECISIONS.md O-01). Image paths, GIF paths, media ids and media attribution fields
are stripped during import. The app shows a placeholder instead.

## License applicable to the imported data and instruction text

Per the source repository, the MIT license covers only its code, tooling, dataset structure and instruction
text/translations:

\`\`\`text
${mitPart}
\`\`\`
`,
);
console.log(`Imported ${exercises.length} exercises from ${PINNED_SHA}`);
